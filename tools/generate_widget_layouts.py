"""Generates Spendly's home-screen widget layouts (app/src/main/res/layout/widget_*.xml).

The layouts share one structure, spacing and type scale, so they are written from this script
rather than by hand. View ids must match WidgetRenderer. Run after editing:

    python3 tools/generate_widget_layouts.py app/src/main/res/layout
"""
import os, sys
OUT = sys.argv[1]
A = 'xmlns:android="http://schemas.android.com/apk/res/android" xmlns:tools="http://schemas.android.com/tools"'
# Static labels in real widgets come from string resources (amounts are set at runtime).
STRINGS = {"Add": "widget_text_add", "Add expense": "widget_text_add_expense", "Spendly": "app_name",
           "Add income": "widget_text_add_income", "Income": "widget_text_income", "Expense": "widget_text_expense",
           "Note it as it comes in": "widget_text_income_tagline",
           "Record it while you remember": "widget_text_tagline", "Last 7 days": "widget_text_last_7_days",
           "Available": "widget_text_available", "Owed on cards": "widget_text_owed_on_cards"}
def label(text, preview):
    if preview or not text:
        return text
    return "@string/" + STRINGS[text]

# Mono Dark colours (the default theme), used only for static launcher-picker previews.
P = dict(bg="#0B0B0C", surface="#151517", elevated="#1F1F22", text="#F5F5F7", muted="#8E8E93",
         accent="#F5F5F7", onAccent="#0B0B0C", track="#2A2A2E", negative="#EE8E8E", positive="#86D3A3")

def tv(id, size, text="", color="text", medium=False, extra="", preview=False, sample=""):
    t = sample if preview else label(text, preview)
    fam = "sans-serif-medium" if medium else "sans-serif"
    col = f'android:textColor="{P[color]}"' if preview else ''
    width = '' if 'layout_width' in extra else 'android:layout_width="wrap_content" '
    return (f'<TextView android:id="@+id/{id}" {width}android:layout_height="wrap_content" '
            f'android:text="{t}" android:textSize="{size}sp" android:fontFamily="{fam}" android:maxLines="1" '
            f'android:ellipsize="end" android:includeFontPadding="false" {col} {extra}/>')

def amount(id, maxsp, minsp=14, preview=False, sample="", height=34, color="text"):
    col = f'android:textColor="{P[color]}"' if preview else ''
    t = sample if preview else ""
    return (f'<TextView android:id="@+id/{id}" android:layout_width="match_parent" android:layout_height="{height}dp" '
            f'android:text="{t}" android:fontFamily="sans-serif-medium" android:fontFeatureSettings="tnum" '
            f'android:maxLines="1" android:includeFontPadding="false" android:gravity="center_vertical|start" '
            f'android:autoSizeTextType="uniform" android:autoSizeMinTextSize="{minsp}sp" android:autoSizeMaxTextSize="{maxsp}sp" '
            f'android:autoSizeStepGranularity="1sp" {col}/>')

def img(id, w, h, src, extra="", preview=False, tint=None):
    t = f'android:tint="{P[tint]}"' if (preview and tint) else ''
    return (f'<ImageView android:id="@+id/{id}" android:layout_width="{w}" android:layout_height="{h}" '
            f'android:src="@drawable/{src}" android:importantForAccessibility="no" {t} {extra}/>')

def root(inner, preview=False, pad="@dimen/widget_padding", orient="vertical", gravity=""):
    g = f'android:gravity="{gravity}"' if gravity else ''
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by tools/generate_widget_layouts.py; keep ids in sync with WidgetRenderer. -->\n'
            f'<FrameLayout {A} android:id="@android:id/background" android:layout_width="match_parent" android:layout_height="match_parent"\n'
            f'    tools:ignore="UselessLeaf,UseCompoundDrawables,NestedWeights{",HardcodedText" if preview else ""}">\n'
            f'  <!-- RemoteViews allow only a few view types: empty FrameLayouts are the spacers, and tinted\n'
            f'       ImageViews stand in for compound drawables, which RemoteViews can\'t tint. -->\n'
            f'  {img("bg", "match_parent", "match_parent", "widget_surface", "android:scaleType=\"fitXY\"", preview, "bg")}\n'
            f'  <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent" android:orientation="{orient}"{' android:baselineAligned="false"' if orient == "horizontal" else ""} android:padding="{pad}" {g}>\n'
            f'{inner}\n  </LinearLayout>\n</FrameLayout>\n')

def button(id, width, label_id=None, label_text="", icon="ic_w_add", icon_id="add_icon", bg_id="add_bg", weight=False, height="match_parent", extra="", preview=False, accent=True, icon_size="22dp", text_size=15, fg=None):
    w = 'android:layout_width="0dp" android:layout_weight="1"' if weight else f'android:layout_width="{width}"'
    tint_bg = "accent" if accent else "elevated"
    tint_fg = fg or ("onAccent" if accent else "accent")
    lab = ''
    if label_id:
        col = f'android:textColor="{P[tint_fg]}"' if preview else ''
        lab = (f'<TextView android:id="@+id/{label_id}" android:layout_width="wrap_content" android:layout_height="wrap_content" '
               f'android:layout_marginStart="8dp" android:text="{label(label_text, preview)}" android:textSize="{text_size}sp" android:fontFamily="sans-serif-medium" '
               f'android:maxLines="1" android:includeFontPadding="false" {col}/>')
    return (f'<FrameLayout android:id="@+id/{id}" {w} android:layout_height="{height}" {extra}>\n'
            f'  {img(bg_id, "match_parent", "match_parent", "widget_inner", "android:scaleType=\"fitXY\"", preview, tint_bg)}\n'
            f'  <LinearLayout android:layout_width="wrap_content" android:layout_height="wrap_content" android:layout_gravity="center" android:orientation="horizontal" android:baselineAligned="false" android:gravity="center_vertical">\n'
            f'    {img(icon_id, icon_size, icon_size, icon, "", preview, tint_fg)}\n    {lab}\n  </LinearLayout>\n</FrameLayout>')

# RemoteViews can't inflate <Space>: an empty FrameLayout is the allowed spacer.
def space(): return '<FrameLayout android:layout_width="match_parent" android:layout_height="0dp" android:layout_weight="1"/>'
def hspace(): return '<FrameLayout android:layout_width="0dp" android:layout_height="1dp" android:layout_weight="1"/>'

def logo_tile(pv):
    return ('<FrameLayout android:id="@+id/logo_tile" android:layout_width="48dp" android:layout_height="match_parent">' +
            img("logo_bg", "match_parent", "match_parent", "widget_inner", 'android:scaleType="fitXY"', pv, "elevated") +
            img("logo", "22dp", "22dp", "ic_w_logo", 'android:layout_gravity="center"', pv, "accent") + '</FrameLayout>')

def header(pv, right_sample):
    """Logo, the app name and one live figure on the right (the large layouts' top row)."""
    return ('<LinearLayout android:layout_width="match_parent" android:layout_height="wrap_content" android:orientation="horizontal" android:baselineAligned="false" android:gravity="center_vertical">' +
            img("logo", "20dp", "20dp", "ic_w_logo", "", pv, "accent") +
            tv("brand", 15, "Spendly", "text", True, 'android:layout_marginStart="8dp" android:layout_width="0dp" android:layout_weight="1"', pv, "MNYBOXD") +
            tv("today", 13, "", "muted", False, 'android:fontFeatureSettings="tnum"', pv, right_sample) + '</LinearLayout>')

